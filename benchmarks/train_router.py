"""Phase 7: train the learned router and measure router regret.

Training data is generated by running **every** candidate model over a task
slice and recording which succeeded. That is expensive by construction: it is
the "run everything once" cost that buys a router which then avoids running
everything forever.

Router regret is measured against a hindsight oracle -- the best achievable
accuracy if the right model had been chosen per item. Reporting the router
without its regret would hide how much of the achievable gain it captures.

Usage::

    python -m benchmarks.train_router --family repurposing_label --limit 60
    python -m benchmarks.train_router --mock --limit 40
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from benchmarks.tasks import load_family
from slmflow.device import probe
from slmflow.models.registry import ModelRegistry
from slmflow.reliability.confidence import normalise_answer
from slmflow.resource.budget import MemoryBudget
from slmflow.resource.residency import ResourceManager
from slmflow.routing.features import feature_vector
from slmflow.routing.heuristic import HeuristicRouter, RandomRouter, router_regret
from slmflow.routing.learned import TrainingExample, train_router
from slmflow.types import SubTask, TaskSpec

__all__ = ["collect_examples", "main"]


def collect_examples(
    registry: ModelRegistry,
    budget: MemoryBudget,
    family_name: str,
    *,
    limit: int = 60,
    split: str = "train",
) -> tuple[list[TrainingExample], dict[tuple[str, str], float], list[SubTask]]:
    """Run every model over a slice, recording per-item outcomes.

    Returns:
        ``(examples, correctness, subtasks)`` where ``correctness`` maps
        ``(item_id, model_id)`` to 1.0/0.0 and is what the oracle needs.

    Raises:
        SystemExit: When fewer than two models fit the budget, since routing
            between one model is not routing.
    """
    kwargs: dict[str, Any] = {"limit": limit}
    if family_name in {"repurposing_label", "grounded_qa"}:
        kwargs["split"] = split
    family = load_family(family_name, **kwargs)
    pool = registry.within_budget(budget)
    if len(pool) < 2:
        raise SystemExit(
            f"Routing needs at least 2 models within {budget.describe()}; "
            f"found {[c.model_id for c in pool]}."
        )

    manager = ResourceManager(budget, measure_on_load=False)
    for card in pool:
        manager.register(card, registry.backend_for(card))

    examples: list[TrainingExample] = []
    correctness: dict[tuple[str, str], float] = {}
    subtasks: list[SubTask] = []

    # Grouped by model so each loads once for the whole slice. Without this the
    # collection run pays len(items) * len(pool) model loads, which on T1 would
    # dominate the entire experiment.
    for position, card in enumerate(pool):
        with manager.resident(card) as handle:
            for item in family.items:
                prompt = family.prompt_template.format(**item.inputs)
                subtask = SubTask(
                    name=family.name,
                    spec=TaskSpec(
                        prompt=prompt,
                        task_type=family.task_type,
                        task_id=item.item_id,
                        output_schema=family.output_schema,
                        max_output_tokens=family.max_output_tokens,
                    ),
                )
                generation = handle.backend.generate(
                    card,
                    prompt,
                    max_tokens=family.max_output_tokens,
                    temperature=0.0,
                    seed=0,
                )
                hit = normalise_answer(generation.text) == normalise_answer(item.gold)
                correctness[(item.item_id, card.model_id)] = 1.0 if hit else 0.0
                examples.append(
                    TrainingExample(
                        features=tuple(feature_vector(subtask)),
                        model_id=card.model_id,
                        reward=1.0 if hit else 0.0,
                    )
                )
                if position == 0:
                    subtasks.append(subtask)
    manager.evict_all()
    return examples, correctness, subtasks


def main(argv: Sequence[str] | None = None) -> int:
    """Train the router, measure regret against baselines, write both."""
    parser = argparse.ArgumentParser(
        prog="python -m benchmarks.train_router",
        description="Train the learned router and measure router regret (Phase 7).",
    )
    parser.add_argument("--family", default="repurposing_label")
    parser.add_argument("--limit", type=int, default=60)
    parser.add_argument("--split", default="train", choices=["train", "test"])
    parser.add_argument("--cards", default="benchmarks/results/model_cards.json")
    parser.add_argument("--out", default="benchmarks/results/router.json")
    parser.add_argument("--report", default="benchmarks/results/router_regret.json")
    parser.add_argument("--epochs", type=int, default=300)
    parser.add_argument("--mock", action="store_true")
    args = parser.parse_args(argv)

    if args.mock:
        from benchmarks.harness import build_registry

        registry = build_registry(mock=True, cards=args.cards)
    else:
        registry = ModelRegistry.from_file(args.cards)

    budget = MemoryBudget.from_device(probe().card)
    examples, correctness, subtasks = collect_examples(
        registry, budget, args.family, limit=args.limit, split=args.split
    )
    sys.stdout.write(f"collected {len(examples)} examples over {len(subtasks)} items\n")

    router = train_router(examples, epochs=args.epochs)
    router.save(args.out)
    sys.stdout.write(f"wrote {args.out}\n")
    if router.report:
        sys.stdout.write(json.dumps(router.report.as_row(), indent=2) + "\n")

    pool = registry.within_budget(budget)
    model_ids = [c.model_id for c in pool]
    rows: list[dict[str, Any]] = []
    for name, candidate in (
        ("learned", router),
        ("heuristic", HeuristicRouter()),
        ("random", RandomRouter(seed=0)),
    ):
        chosen = [(st.spec.task_id, candidate.select(st, pool).model_id) for st in subtasks]
        rows.append(router_regret(name, chosen, correctness, model_ids).as_row())

    # Static baselines: one row per model, always chosen. These are what a
    # framework without a router achieves, and the router must beat them.
    for model_id in model_ids:
        chosen = [(st.spec.task_id, model_id) for st in subtasks]
        rows.append(
            router_regret(f"static:{model_id}", chosen, correctness, model_ids).as_row()
        )

    report = {
        "family": args.family,
        "split": args.split,
        "n_items": len(subtasks),
        "models": model_ids,
        "rows": rows,
        "train_report": router.report.as_row() if router.report else None,
        "note": (
            "With --split train the router is evaluated on the slice it was trained on. "
            "Run --split test for a held-out number before citing it anywhere."
        ),
    }
    report_path = Path(args.report)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")

    sys.stdout.write("\n")
    sys.stdout.write(f"{'router':<28} {'acc':>7} {'oracle':>7} {'regret':>8}\n")
    sys.stdout.write("-" * 54 + "\n")
    for row in rows:
        sys.stdout.write(
            f"{str(row['router']):<28} {row['router_accuracy']:>7.3f} "
            f"{row['oracle_accuracy']:>7.3f} {row['regret']:>8.3f}\n"
        )
    sys.stdout.write(f"\nwrote {report_path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
